/**
 * Locale registry + dictionary for EasyInvoiceOCR.
 *
 * Three locales ship as real routes: English, French, Arabic (RTL).
 * Every user-visible string in chrome, forms and validation lives here so a
 * page can never render mixed-language UI.
 */

export const locales = ["en", "fr", "ar"] as const;
export type Locale = (typeof locales)[number];
export const defaultLocale: Locale = "en";

export const localeLabels: Record<Locale, string> = {
  en: "English",
  fr: "Français",
  ar: "العربية",
};

export const localeDir: Record<Locale, "ltr" | "rtl"> = {
  en: "ltr",
  fr: "ltr",
  ar: "rtl",
};

export const localeHtmlLang: Record<Locale, string> = {
  en: "en",
  fr: "fr",
  ar: "ar",
};

export function isLocale(value: unknown): value is Locale {
  return typeof value === "string" && (locales as readonly string[]).includes(value);
}

/**
 * Reads the locale out of a URL path, e.g. "/ar/blog/x" → "ar".
 *
 * Used by the document shell, which renders above the route tree and so has no
 * route params to read. Anything unrecognised falls back to the default rather
 * than throwing: a shell that cannot render is worse than one that renders in
 * English.
 */
export function localeFromPathname(pathname: string): Locale {
  const first = pathname.split("?")[0]!.split("#")[0]!.split("/").filter(Boolean)[0];
  return isLocale(first) ? first : defaultLocale;
}

export function asLocale(value: unknown): Locale {
  return isLocale(value) ? value : defaultLocale;
}

/** Locale-aware date formatting (Gregorian calendar in every locale). */
export function formatDate(iso: string, locale: Locale): string {
  const date = new Date(iso);
  return new Intl.DateTimeFormat(locale === "ar" ? "ar-u-ca-gregory-nu-latn" : locale, {
    year: "numeric",
    month: "long",
    day: "numeric",
  }).format(date);
}

export function formatNumber(value: number, locale: Locale): string {
  return new Intl.NumberFormat(locale === "ar" ? "ar-u-nu-latn" : locale).format(value);
}

