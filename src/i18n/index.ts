export const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, fr, ar };

export type MessageParams = Record<string, string | number>;

/**
 * Looks up a message and fills any {placeholders}. A missing placeholder is
 * left as written rather than replaced with "undefined", so a translation gap
 * is visible instead of silently corrupting a sentence.
 */
export function translate(locale: Locale, key: MessageKey, params?: MessageParams): string {
  const message = dictionaries[locale][key];
  if (!params) return message;
  return message.replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in params ? String(params[name]) : whole,
  );
}
